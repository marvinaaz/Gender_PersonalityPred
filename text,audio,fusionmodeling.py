# Function to create SHAP table for a subset
def create_shap_table(shap_values, features, traits, subset_name):
    """
    Create a table of mean absolute SHAP values for a given subset.

    Parameters:
    - shap_values: SHAP values array [n_samples, n_features, n_outputs]
    - features: List of feature names
    - traits: List of personality trait names
    - subset_name: Name of the subset ('Male', 'Female', 'Combined')

    Returns:
    - DataFrame with mean absolute SHAP values
    """
    # Compute mean absolute SHAP values across samples for each feature and trait
    mean_abs_shap = np.abs(shap_values).mean(axis=0)  # Shape: [n_features, n_outputs]

    # Create DataFrame
    df = pd.DataFrame(mean_abs_shap, index=features, columns=traits)
    df.index.name = 'Feature'
    df = df.round(4)  # Round to 4 decimal places for readability

    return df

