from sklearn.linear_model import LinearRegression

def late_fusion(text_preds, acoustic_preds, y_true):
    try:
        X_fusion = np.hstack([text_preds, acoustic_preds])
        fusion_model = LinearRegression()
        fusion_model.fit(X_fusion, y_true)
        return fusion_model.predict(X_fusion)
    except Exception as e:
        return np.zeros_like(y_true)

