# Evaluation
def evaluate_model(y_true, y_pred):
    try:
        mae = mean_absolute_error(y_true, y_pred, multioutput='raw_values')
        return {'mae_per_trait': dict(zip(target_cols, mae)), 'mae_mean': mae.mean()}
    except Exception as e:
        return {'mae_per_trait': {col: np.nan for col in target_cols}, 'mae_mean': np.nan}

# Bias Analysis
def compute_shap_values(model, X):
    try:
        explainer = shap.TreeExplainer(model)
        shap_values = explainer.shap_values(X)
        return shap_values
    except Exception as e:
        return None

def statistical_tests(male_errors, female_errors):
    try:
        t_stat, p_val = ttest_ind(male_errors, female_errors, equal_var=False)
        f_stat, p_val_anova = f_oneway(male_errors, female_errors)
        return {'t_test_p': p_val, 'anova_p': p_val_anova}
    except Exception as e:
        return {'t_test_p': np.nan, 'anova_p': np.nan}

def compute_spd(male_preds, female_preds):
    try:
        ks_stat, _ = ks_2samp(male_preds, female_preds)
        return ks_stat
    except Exception as e:
        print(f"Error in SPD computation: {e}")
        return np.nan

def compute_gnpd(male_preds, female_preds):
    try:
        n_m, n_f = len(male_preds), len(female_preds)
        sigma_m, sigma_f = np.std(male_preds), np.std(female_preds)
        norm_factor = np.sqrt(sigma_m**2 + sigma_f**2) + 1e-10
        if norm_factor == 0:
            return 0
        diff_sum = sum(abs(m - f) for m in male_preds for f in female_preds)
        return diff_sum / (n_m * n_f * norm_factor)
    except Exception as e:
        print(f"Error in GNPD computation: {e}")
        return np.nan

def compute_cfs(test_data_male, test_data_female, pred_cols, w1=0.5, w2=0.5):
    cfs_scores = {}
    for col in pred_cols:
        male_preds = test_data_male[col].dropna().values
        female_preds = test_data_female[col].dropna().values
        if len(male_preds) == 0 or len(female_preds) == 0:
            print(f"No valid predictions for {col}")
            cfs_scores[col.replace('pred_', '')] = np.nan
            continue
        spd = compute_spd(male_preds, female_preds)
        gnpd = compute_gnpd(male_preds, female_preds)
        cfs = w1 * spd + w2 * gnpd
        cfs_scores[col.replace('pred_', '')] = cfs
    return cfs_scores

