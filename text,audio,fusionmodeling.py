def extract_transcripts(file_path, group_id, speaker_map):
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            text = f.read()
            pattern = r'(\d+:\d+:\d+(?:\.\d+)?)\t([^\t]+)\t(.*?)(?=\n\d+:\d+:\d+(?:\.\d+)?|\Z)'
            matches = re.findall(pattern, text, re.DOTALL)
            speaker_transcripts = {}
            for _, speaker, transcript in matches:
                transcript = transcript.strip()
                if transcript and not re.match(r'^\(.*\)$', transcript):
                    if speaker not in speaker_transcripts:
                        speaker_transcripts[speaker] = []
                    speaker_transcripts[speaker].append(transcript)
            group_speaker_map = speaker_map[speaker_map['idGp'] == group_id]
            if group_speaker_map.empty:
                return
            for speaker, texts in speaker_transcripts.items():
                transcript = " ".join(texts)
                if 'Male' in speaker:
                    gender = 'Male'
                    match = re.search(r'Male (\d+)', speaker)
                    track_id = int(match.group(1)) if match else 0
                elif 'Female' in speaker:
                    gender = 'Female'
                    match = re.search(r'Female (\d+)', speaker)
                    track_id = int(match.group(1)) if match else 0
                else:
                    continue
                match = group_speaker_map[(group_speaker_map['GenderValue'] == (2 if gender == 'Female' else 1)) &
                                         (group_speaker_map['idTRack'] == track_id)]
                if not match.empty:
                    letter_id = match['Letter'].iloc[0]
                    transcriptions.append({
                        'group': group_id,
                        'letterId': letter_id,
                        'transcript': transcript
                    })
    except Exception as e:
        print(f"Error processing file {file_path}: {e}")

