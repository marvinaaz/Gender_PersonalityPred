"""# Text - Based Modeling"""

tokenizer = DistilBertTokenizer.from_pretrained('distilbert-base-uncased')
def tokenize_text(texts, max_length=512):
    # Tokenize all texts at once to ensure consistent padding
    encodings = tokenizer(
        texts.tolist(),  # Convert pandas Series to list
        truncation=True,
        padding='max_length',  # Pad to max_length
        max_length=max_length,
        return_tensors='pt'
    )
    return encodings['input_ids'], encodings['attention_mask']

class DistilBERTPersonality(torch.nn.Module):
    def __init__(self):
        super(DistilBERTPersonality, self).__init__()
        self.distilbert = DistilBertModel.from_pretrained('distilbert-base-uncased')
        self.fc = torch.nn.Linear(768, 5)  # 5 for Big Five personality traits

    def forward(self, input_ids, attention_mask):
        outputs = self.distilbert(input_ids=input_ids, attention_mask=attention_mask)
        pooled_output = outputs.last_hidden_state[:, 0]
        return self.fc(pooled_output)

def train_text_model(data, target_cols, batch_size=8):
    model = DistilBERTPersonality().to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=2e-5)
    criterion = torch.nn.MSELoss()

    input_ids, attention_mask = tokenize_text(data['transcript'])
    if input_ids is None:
        raise ValueError("Tokenization failed")
    targets = torch.tensor(data[target_cols].values, dtype=torch.float32).to(device)

    model.train()
    for i in range(0, len(data), batch_size):
        batch_input_ids = input_ids[i:i+batch_size]
        batch_attention_mask = attention_mask[i:i+batch_size]
        batch_targets = targets[i:i+batch_size]

        optimizer.zero_grad()
        outputs = model(batch_input_ids, batch_attention_mask)
        loss = criterion(outputs, batch_targets)
        loss.backward()
        optimizer.step()

    return model

def predict_text_model(model, data):
    input_ids, attention_mask = tokenize_text(data['transcript'])
    if input_ids is None:
        raise ValueError("Tokenization failed")
    model.eval()
    with torch.no_grad():
        preds = model(input_ids, attention_mask).cpu().numpy()
    return preds

