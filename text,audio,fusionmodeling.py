scaler = StandardScaler()

def preprocess_acoustic(data, features):
    try:
        data_subset = data[features].dropna()
        if data_subset.empty:
            raise ValueError("No valid acoustic data after dropping NaNs")
        scaled_features = scaler.fit_transform(data_subset)
        return pd.DataFrame(scaled_features, columns=features, index=data_subset.index)
    except Exception as e:
        return pd.DataFrame()

def train_acoustic_model(data, features, target_cols):
    X = preprocess_acoustic(data, features)
    if X.empty:
        raise ValueError("Acoustic preprocessing failed")
    y = data.loc[X.index, target_cols]
    model = RandomForestRegressor(n_estimators=100, random_state=42)
    model.fit(X, y)
    return model

def predict_acoustic_model(model, data, features):
    X = preprocess_acoustic(data, features)
    if X.empty:
        raise ValueError("Acoustic preprocessing failed")
    return model.predict(X)

