"""
Calculate Pearson correlations between acoustic features and Big Five personality traits
and visualize as a heatmap.
"""

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

# Load the dataset (adjust path as needed)
master_df = pd.read_csv('/content/drive/MyDrive/MRP_w_Nancy/Final_Deliverable/combined_features_with_transcripts.csv')

# Define acoustic features and Big Five personality traits
acoustic_features = ['pitch_mean', 'pitch_std', 'pitch_range', 'intensity_mean',
                     'intensity_std', 'spectral_centroid_mean', 'spectral_centroid_std',
                     'speaking_rate']
target_cols = ['EXTROV.MEDIA.NEO', 'NEUROTIC.MEDIA.NEO', 'OPENNESS.MEDIA.NEO',
               'AGREAB.MEDIA.NEO', 'CONSCIENT.MEDIA.NEO']

# Filter DataFrame to include only relevant columns and drop rows with missing values
data = master_df[acoustic_features + target_cols].dropna()

# Calculate Pearson correlation matrix
correlation_matrix = data.corr(method='pearson')

# Extract correlations between acoustic features and personality traits
corr_acoustic_traits = correlation_matrix.loc[acoustic_features, target_cols]

# Create heatmap visualization
plt.figure(figsize=(10, 6))
sns.heatmap(corr_acoustic_traits, annot=True, cmap='coolwarm', center=0,
            vmin=-1, vmax=1, fmt='.2f')
plt.title('Correlation Between Acoustic Features and Big Five Personality Traits')
plt.xlabel('Personality Traits')
plt.ylabel('Acoustic Features')
plt.tight_layout()

# Save the plot for inclusion in the paper
plt.savefig('/content/drive/MyDrive/MRP_w_Nancy/Final_Deliverable/correlation_heatmap.png', dpi=300)
plt.close()

