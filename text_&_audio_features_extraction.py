def extract_group_number(filename):
    """Extract group number from filename (e.g., G20 from 20100408-160401_G20.csv)"""
    try:
        return int(filename.stem.split('_G')[-1])
    except (IndexError, ValueError):
        return None

def extract_audio_features(csv_file):
    """Extract audio features for each person in the CSV file"""
    try:
        # Extract group number from CSV filename
        group_num = extract_group_number(csv_file)
        if group_num is None:
            return pd.DataFrame()

        # Load segmentation data
        seg_file = csv_file
        df = pd.read_csv(seg_file)

        # Load audio file
        audio_file = wav_base / f'group{group_num}.wav'
        if not audio_file.exists():
            print(f"WAV file not found: {audio_file}")
            return pd.DataFrame()

        y, sr = librosa.load(audio_file, sr=None)

        # Group segments by person
        grouped = df.groupby('person')

        features = []
        for person, group in grouped:
            # Combine all segments for this person
            segments = [y[int(row['start']*sr):int(row['end']*sr)]
                       for _, row in group.iterrows() if row['start'] < row['end']]
            if not segments:
                continue
            combined_segment = np.concatenate(segments)

            # Extract comprehensive audio features
            audio_features = extract_comprehensive_features(combined_segment, sr)
            audio_features['person'] = person
            audio_features['group'] = group_num
            audio_features['file_name'] = csv_file.name
            features.append(audio_features)

        return pd.DataFrame(features)

    except Exception as e:
        return pd.DataFrame()

def extract_comprehensive_features(segment, sr):
    """Extract comprehensive audio features from a segment"""
    features = {}

    # Pitch features
    f0, voiced_flag, _ = librosa.pyin(segment, fmin=librosa.note_to_hz('C2'), fmax=librosa.note_to_hz('C7'))
    f0 = f0[voiced_flag]
    features.update({
        'pitch_mean': np.mean(f0) if len(f0) > 0 else 0,
        'pitch_std': np.std(f0) if len(f0) > 0 else 0,
        'pitch_range': np.ptp(f0) if len(f0) > 0 else 0,
        'pitch_skew': skew(f0) if len(f0) > 2 else 0,
        'pitch_kurtosis': kurtosis(f0) if len(f0) > 3 else 0
    })

    # Intensity/Energy features
    rms = librosa.feature.rms(y=segment)[0]
    features.update({
        'intensity_mean': np.mean(rms) if len(rms) > 0 else 0,
        'intensity_std': np.std(rms) if len(rms) > 0 else 0,
        'intensity_max': np.max(rms) if len(rms) > 0 else 0,
        'intensity_min': np.min(rms) if len(rms) > 0 else 0
    })

    # Temporal features
    duration = librosa.get_duration(y=segment, sr=sr)
    features.update({
        'speaking_duration': duration,
        'speaking_rate': len(segment)/duration if duration > 0 else 0,
        'articulation_rate': len(librosa.effects.preemphasis(segment))/duration if duration > 0 else 0
    })

    # Spectral features
    spectral_centroid = librosa.feature.spectral_centroid(y=segment, sr=sr)[0]
    spectral_bandwidth = librosa.feature.spectral_bandwidth(y=segment, sr=sr)[0]
    features.update({
        'spectral_centroid_mean': np.mean(spectral_centroid) if len(spectral_centroid) > 0 else 0,
        'spectral_centroid_std': np.std(spectral_centroid) if len(spectral_centroid) > 0 else 0,
        'spectral_bandwidth_mean': np.mean(spectral_bandwidth) if len(spectral_bandwidth) > 0 else 0,
        'spectral_bandwidth_std': np.std(spectral_bandwidth) if len(spectral_bandwidth) > 0 else 0
    })

    # Voice quality features
    harmonic_ratio = librosa.effects.harmonic(segment)
    features.update({
        'harmonic_ratio': np.mean(harmonic_ratio) if len(harmonic_ratio) > 0 else 0,
        'noise_ratio': 1 - np.mean(harmonic_ratio) if len(harmonic_ratio) > 0 else 1
    })

    return features

